"""Compile the product token source to CSS, without third-party dependencies.

python scripts/build-design-tokens.py [--check]
--check also guards accidental drift between the source and generated CSS.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'design-system/smart-home-calc/tokens.json'
TARGET = ROOT / 'frontend/src/design-system/tokens.css'


def variables(group, path=()):
    for name, value in group.items():
        if name.startswith('$') or name == 'contrastPairs':
            continue
        key = (*path, name)
        if '$value' not in value:
            yield from variables(value, key)
            continue
        raw, kind = value['$value'], value['$type']
        if kind in ('dimension', 'duration'):
            raw = str(raw['value']) + raw['unit']
        elif kind == 'fontFamily':
            raw = ', '.join('"'+v+'"' if ' ' in v else v for v in raw)
        yield '--ds-' + '-'.join(key), str(raw)


def luminance(hex_color):
    values = [int(hex_color[i:i+2], 16) / 255 for i in (1, 3, 5)]
    values = [v / 12.92 if v <= .04045 else ((v+.055)/1.055)**2.4 for v in values]
    return sum(v * w for v, w in zip(values, (.2126, .7152, .0722)))


def compile_tokens(check=False):
    data = json.loads(SOURCE.read_text(encoding='utf-8'))
    for foreground, background, minimum in data['$extensions']['smart-home-calc']['contrastPairs']:
        fg, bg = [luminance(data['color'][key]['$value']) for key in (foreground, background)]
        ratio = (max(fg, bg)+.05) / (min(fg, bg)+.05)
        if ratio < minimum:
            raise SystemExit(f'Contrast {foreground}/{background}: {ratio:.2f} < {minimum}')
    entries = list(variables(data))
    css = '/* Generated by scripts/build-design-tokens.py; edit tokens.json. */\n:root {\n'
    css += ''.join(f'  {name}: {value};\n' for name, value in entries) + '}\n'
    if check:
        if not TARGET.exists() or TARGET.read_text(encoding='utf-8') != css:
            raise SystemExit('Token CSS is stale. Run python scripts/build-design-tokens.py.')
    else:
        TARGET.parent.mkdir(parents=True, exist_ok=True)
        TARGET.write_text(css, encoding='utf-8')
    print(f'{len(entries)} tokens · {len(data["$extensions"]["smart-home-calc"]["contrastPairs"])} contrast pairs · '+('checked' if check else 'generated'))


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    compile_tokens(parser.parse_args().check)
